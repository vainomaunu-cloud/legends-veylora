const FONT = {};
(function buildFont() {
  for (const ch in FONT_SRC) {
    const rows = FONT_SRC[ch].split('|');
    FONT[ch] = { rows, w: rows[0].length };
  }
})();

const FONT_SPACE = 3;
const FONT_GAP = 1;

function glyphOf(ch) { return FONT[ch] || FONT['?']; }

function textWidth(s) {
  let w = 0;
  for (const ch of String(s).toUpperCase()) w += (ch === ' ' ? FONT_SPACE : glyphOf(ch).w) + FONT_GAP;
  return Math.max(0, w - FONT_GAP);
}

// Draws text; returns the x after the last glyph.
function drawText(g, s, x, y, color = '#283040', scale = 1) {
  g.fillStyle = color;
  let cx = x;
  for (const ch of String(s).toUpperCase()) {
    if (ch === ' ') { cx += (FONT_SPACE + FONT_GAP) * scale; continue; }
    const gl = glyphOf(ch);
    for (let r = 0; r < 7; r++) {
      const row = gl.rows[r];
      for (let c = 0; c < gl.w; c++) if (row[c] === '#') g.fillRect(cx + c * scale, y + r * scale, scale, scale);
    }
    cx += (gl.w + FONT_GAP) * scale;
  }
  return cx;
}

function drawTextRight(g, s, rightX, y, color, scale = 1) {
  drawText(g, s, rightX - textWidth(s) * scale, y, color, scale);
}

function drawTextCenter(g, s, cx, y, color, scale = 1) {
  drawText(g, s, Math.round(cx - textWidth(s) * scale / 2), y, color, scale);
}

// Word-wrap to lines no wider than maxW. '\n' forces a break.
function wrapText(s, maxW) {
  const out = [];
  for (const para of String(s).split('\n')) {
    let cur = '';
    for (const word of para.split(' ')) {
      const t = cur ? cur + ' ' + word : word;
      if (textWidth(t) <= maxW || !cur) cur = t; else { out.push(cur); cur = word; }
    }
    out.push(cur);
  }
  return out;
}
